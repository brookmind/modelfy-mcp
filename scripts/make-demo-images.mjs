// Draws the sandbox demo product (a linen T-shirt, front and back) as PNGs
// and writes them into src/sandbox-demo-assets.ts as base64, so the Worker
// serves them without any file storage.
// Usage: node scripts/make-demo-images.mjs
import { Buffer } from "node:buffer";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "sandbox-demo-assets.ts");
const WIDTH = 480;
const HEIGHT = 600;
const BACKGROUND = [236, 233, 226];
const SHIRT = [196, 170, 132];
const SHADE = [176, 150, 112];
const COLLAR = [150, 126, 92];

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(bytes) {
  let c = 0xffffffff;
  for (const byte of bytes) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

/** True inside the T-shirt silhouette (body plus both sleeves). */
function inShirt(x, y) {
  const body = x >= 150 && x <= 330 && y >= 130 && y <= 540;
  const shoulder = y >= 110 && y <= 140 && x >= 130 && x <= 350;
  const leftSleeve =
    y >= 120 && y <= 260 && x >= 70 && x < 150 && y - 120 >= (150 - x) * 0.6;
  const rightSleeve =
    y >= 120 && y <= 260 && x > 330 && x <= 410 && y - 120 >= (x - 330) * 0.6;
  return body || shoulder || leftSleeve || rightSleeve;
}

function pixel(x, y, side) {
  if (!inShirt(x, y)) return BACKGROUND;
  const dx = x - 240;
  // Front: a round neckline; back: a thin collar band
  const neck =
    side === "front"
      ? dx * dx + (y - 110) * (y - 110) <= 45 * 45
      : y <= 125 && Math.abs(dx) <= 50;
  if (neck) return side === "front" ? BACKGROUND : COLLAR;
  if (side === "front" && dx * dx + (y - 110) * (y - 110) <= 52 * 52) {
    return COLLAR;
  }
  return x > 300 || y > 500 ? SHADE : SHIRT;
}

function png(side) {
  const rows = [];
  for (let y = 0; y < HEIGHT; y++) {
    const row = Buffer.alloc(1 + WIDTH * 3);
    for (let x = 0; x < WIDTH; x++) {
      const [r, g, b] = pixel(x, y, side);
      row[1 + x * 3] = r;
      row[2 + x * 3] = g;
      row[3 + x * 3] = b;
    }
    rows.push(row);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(WIDTH, 0);
  header.writeUInt32BE(HEIGHT, 4);
  header[8] = 8; // bit depth
  header[9] = 2; // RGB
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(Buffer.concat(rows), { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const front = png("front").toString("base64");
const back = png("back").toString("base64");
writeFileSync(
  OUT,
  `// Generated by scripts/make-demo-images.mjs. Do not edit.
/** The sandbox demo product's photos (PNG, base64). */
export const DEMO_TEE_FRONT_PNG =
  "${front}";
export const DEMO_TEE_BACK_PNG =
  "${back}";
`,
);
console.log(
  `demo images: ${front.length + back.length} base64 chars -> ${OUT}`,
);
