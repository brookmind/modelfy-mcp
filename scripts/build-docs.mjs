// Compiles docs/*.md into src/docs/content.ts, so the Worker serves the same
// documentation people read on GitHub (no file system at runtime).
// Usage: node scripts/build-docs.mjs [--check]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const DOCS_DIR = join(ROOT, "docs");
const OUT = join(ROOT, "src", "docs", "content.ts");
const FIELDS = ["title", "description", "order"];

function parse(file) {
  const raw = readFileSync(join(DOCS_DIR, file), "utf8");
  const match = /^---\n([\s\S]*?)\n---\n+([\s\S]*)$/.exec(raw);
  if (match === null) throw new Error(`${file}: missing front matter`);
  const meta = {};
  for (const line of match[1].split("\n")) {
    const at = line.indexOf(":");
    if (at > 0) meta[line.slice(0, at).trim()] = line.slice(at + 1).trim();
  }
  for (const field of FIELDS) {
    if (!meta[field]) throw new Error(`${file}: front matter needs ${field}`);
  }
  return {
    slug: basename(file, ".md"),
    title: meta.title,
    description: meta.description,
    order: Number(meta.order),
    markdown: match[2].trimEnd() + "\n",
  };
}

const pages = readdirSync(DOCS_DIR)
  .filter((file) => file.endsWith(".md"))
  .map(parse)
  .sort((a, b) => a.order - b.order)
  .map(({ slug, title, description, markdown }) => ({
    slug,
    title,
    description,
    markdown,
  }));

const source = `// Generated by scripts/build-docs.mjs from docs/*.md. Do not edit.
import type { DocPage } from "./types";

export const DOC_PAGES: readonly DocPage[] = ${JSON.stringify(pages, null, 2)};
`;

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== source) {
    console.error("src/docs/content.ts is out of date: run npm run docs:build");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, source);
  console.log(`${pages.length} pages -> src/docs/content.ts`);
}
